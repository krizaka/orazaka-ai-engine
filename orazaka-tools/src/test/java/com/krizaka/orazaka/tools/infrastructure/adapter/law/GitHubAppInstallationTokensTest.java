package com.krizaka.orazaka.tools.infrastructure.adapter.law;

import static com.krizaka.orazaka.tools.infrastructure.adapter.law.RecordedGitHub.API;
import static com.krizaka.orazaka.tools.infrastructure.adapter.law.RecordedGitHub.answer;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.*;
import static org.springframework.test.web.client.response.MockRestResponseCreators.withSuccess;

import java.nio.charset.StandardCharsets;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.NoSuchAlgorithmException;
import java.security.Signature;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.Base64;
import org.hamcrest.Matchers;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.test.web.client.ExpectedCount;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.web.client.RestClient;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The App's installation tokens on a recorded GitHub API: a signed App JWT, one token per hour, and
 * the private key read as GitHub gives it. The key is generated by the test, never committed.
 */
class GitHubAppInstallationTokensTest {

  private static final Instant NOW = Instant.parse("2026-10-24T12:00:00Z");
  private static final KeyPair KEYS = keys();

  private static KeyPair keys() {
    try {
      KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
      generator.initialize(2048);
      return generator.generateKeyPair();
    } catch (NoSuchAlgorithmException e) {
      throw new IllegalStateException(e);
    }
  }

  @Test
  void the_app_jwt_is_rs256_signed_issued_by_the_app_and_short() throws Exception {
    String jwt = GitHubAppInstallationTokens.jwt("424242", KEYS.getPrivate(), NOW);

    String[] parts = jwt.split("\\.");
    assertThat(parts).hasSize(3);
    Signature rsa = Signature.getInstance("SHA256withRSA");
    rsa.initVerify(KEYS.getPublic());
    rsa.update((parts[0] + "." + parts[1]).getBytes(StandardCharsets.US_ASCII));
    assertThat(rsa.verify(Base64.getUrlDecoder().decode(parts[2]))).isTrue();
    JsonNode claims =
        JsonMapper.builder().build().readTree(Base64.getUrlDecoder().decode(parts[1]));
    assertThat(claims.path("iss").asString()).isEqualTo("424242");
    assertThat(claims.path("exp").asLong() - claims.path("iat").asLong()).isLessThanOrEqualTo(600);
    assertThat(claims.path("iat").asLong()).isLessThan(NOW.getEpochSecond());
  }

  @Test
  void one_token_is_minted_and_reused_until_shortly_before_it_ends() {
    RestClient.Builder builder = RestClient.builder().baseUrl(API);
    MockRestServiceServer server = MockRestServiceServer.bindTo(builder).build();
    server
        .expect(ExpectedCount.twice(), requestTo(API + "/app/installations/7/access_tokens"))
        .andExpect(method(HttpMethod.POST))
        .andExpect(header("Authorization", Matchers.startsWith("Bearer ey")))
        .andRespond(withSuccess(answer("installation-token.json"), MediaType.APPLICATION_JSON));
    MutableClock clock = new MutableClock(NOW);
    GitHubAppInstallationTokens tokens =
        new GitHubAppInstallationTokens(builder.build(), "424242", 7, KEYS.getPrivate(), clock);

    assertThat(tokens.token()).isEqualTo("recorded-installation-token");
    clock.now = NOW.plusSeconds(50 * 60);
    assertThat(tokens.token()).isEqualTo("recorded-installation-token");
    clock.now = NOW.plusSeconds(56 * 60);
    tokens.token();

    server.verify();
  }

  @Test
  void the_private_key_is_read_as_pkcs8_and_as_github_gives_it_pkcs1() {
    byte[] pkcs8 = KEYS.getPrivate().getEncoded();
    String pem8 = pem("PRIVATE KEY", pkcs8);
    // PKCS#8 holds the PKCS#1 key as its last OCTET STRING: 26 bytes of header for a 2048-bit key.
    byte[] pkcs1 = java.util.Arrays.copyOfRange(pkcs8, 26, pkcs8.length);
    String pem1 = pem("RSA PRIVATE KEY", pkcs1);

    assertThat(GitHubAppInstallationTokens.privateKey(pem8)).isEqualTo(KEYS.getPrivate());
    assertThat(GitHubAppInstallationTokens.privateKey(pem1).getEncoded()).isEqualTo(pkcs8);
    assertThatThrownBy(() -> GitHubAppInstallationTokens.privateKey("not a key"))
        .isInstanceOf(IllegalArgumentException.class);
    assertThatThrownBy(() -> GitHubAppInstallationTokens.privateKey(" "))
        .isInstanceOf(IllegalArgumentException.class);
  }

  @Test
  void an_app_names_its_id_and_its_installation() {
    RestClient client = RestClient.create(API);
    Clock clock = Clock.fixed(NOW, ZoneOffset.UTC);

    assertThatThrownBy(
            () -> new GitHubAppInstallationTokens(client, " ", 7, KEYS.getPrivate(), clock))
        .isInstanceOf(IllegalArgumentException.class);
    assertThatThrownBy(
            () -> new GitHubAppInstallationTokens(client, "424242", 0, KEYS.getPrivate(), clock))
        .isInstanceOf(IllegalArgumentException.class);
  }

  private static String pem(String type, byte[] der) {
    return "-----BEGIN "
        + type
        + "-----\n"
        + Base64.getMimeEncoder(64, "\n".getBytes(StandardCharsets.US_ASCII)).encodeToString(der)
        + "\n-----END "
        + type
        + "-----\n";
  }

  private static final class MutableClock extends Clock {
    Instant now;

    MutableClock(Instant now) {
      this.now = now;
    }

    @Override
    public java.time.ZoneId getZone() {
      return ZoneOffset.UTC;
    }

    @Override
    public Clock withZone(java.time.ZoneId zone) {
      return this;
    }

    @Override
    public Instant instant() {
      return now;
    }
  }
}
